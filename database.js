// Local Storage Helper to manage database custom edits
const STORAGE_KEY = "AI_SPARKX_TEAM_DB_V9";

export function getDatabase() {
  const customDb = localStorage.getItem(STORAGE_KEY);
  if (customDb) {
    try {
      const parsed = JSON.parse(customDb);
      if (Array.isArray(parsed) && parsed.length >= 50 && parsed[0]?.puzzle?.piecesCount === 36) {
        return parsed;
      }
    } catch (e) {
      console.error("Failed to parse custom database from localStorage", e);
    }
  }
  // Clear any legacy keys from older versions
  try {
    localStorage.removeItem("AI_SPARKX_TEAM_DB_V1");
    localStorage.removeItem("AI_SPARKX_TEAM_DB_V2");
    localStorage.removeItem("AI_SPARKX_TEAM_DB_V3");
    localStorage.removeItem("AI_SPARKX_TEAM_DB_V4");
    localStorage.removeItem("AI_SPARKX_TEAM_DB_V5");
    localStorage.removeItem("AI_SPARKX_TEAM_DB_V6");
    localStorage.removeItem("AI_SPARKX_TEAM_DB_V7");
    localStorage.removeItem("AI_SPARKX_TEAM_DB_V8");
  } catch (e) {}

  return DEFAULT_DATABASE;
}

export function saveDatabase(data) {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
}

export function resetDatabase() {
  localStorage.removeItem(STORAGE_KEY);
  return DEFAULT_DATABASE;
}

export function findTeam(teamId) {
  const db = getDatabase();
  const cleanId = String(teamId).trim().toLowerCase();
  return db.find(t => String(t.id).trim().toLowerCase() === cleanId) || null;
}
